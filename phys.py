def _as_float_array(T):
    """Convert T to a float ndarray, remembering whether it was scalar."""
    arr = np.asarray(T, dtype=float)
    is_scalar = arr.ndim == 0
    return np.atleast_1d(arr), is_scalar


def _finalize(Theta, dTheta, is_scalar):
    if is_scalar:
        return {"Theta": float(Theta[0]), "dTheta": float(dTheta[0])}
    return {"Theta": Theta, "dTheta": dTheta}


def _result(x, is_scalar):
    """Return x as a plain float if the input was scalar, else as an ndarray."""
    if is_scalar:
        return float(np.asarray(x).reshape(-1)[0])
    return np.asarray(x, dtype=float)


def _lunardini(T, Tf=0.0, w=0.5):
    """Lunardini (1981) freezing-point-depression partition function.

    Direct translation of ftheta_lunardini.m / the "lun"/"l" branch of
    ftheta.m.
    """
    T, is_scalar = _as_float_array(T)
    Tf = float(Tf)
    w = float(w)

    Theta = np.exp(-(((T - Tf) / w) ** 2))
    frozen_out = T > Tf
    Theta[frozen_out] = 1.0

    a = -2.0 / (w * w)
    dTheta = a * (T - Tf) * Theta
    dTheta[frozen_out] = 0.0

    return _finalize(Theta, dTheta, is_scalar)


def _galushkin(T, Tf=0.0):
    """Galushkin (1997) polynomial partition function.

    Direct translation of ftheta_galushkin.m / the "gal"/"g" branch of
    ftheta.m. The polynomial coefficients are copied verbatim from the
    MATLAB source.
    """
    T, is_scalar = _as_float_array(T)
    Tf = float(Tf)

    a0 = 1.0
    a1 = 0.60152823763179
    a2 = 0.23218232347212
    a3 = 0.04669792788297
    a4 = 0.00535597924776
    a5 = 0.00036415588418
    a6 = 0.00001450956751
    a7 = 0.00000031279149
    a8 = 0.00000000281502

    Theta = (
        a0
        + a1 * T
        + a2 * T**2
        + a3 * T**3
        + a4 * T**4
        + a5 * T**5
        + a6 * T**6
        + a7 * T**7
        + a8 * T**8
    )
    frozen_out = T > Tf
    Theta[frozen_out] = 1.0

    dTheta = (
        a1
        + 2 * a2 * T
        + 3 * a3 * T**2
        + 4 * a4 * T**3
        + 5 * a5 * T**4
        + 6 * a6 * T**5
        + 7 * a7 * T**6
        + 8 * a8 * T**7
    )
    dTheta[frozen_out] = 0.0

    return _finalize(Theta, dTheta, is_scalar)


def _nicolsky(T, Tf=-0.001, p=0.5):
    """Nicolsky, Romanovsky & Tipenko (2007) power-law partition function.

    Follows the "nic"/"n" branch of the ftheta.m dispatcher (including its
    parameter validation), rather than the standalone ftheta_nicolsky.m
    file. The standalone file has an unrelated third argument (`p`) that
    is used in the formula but never given a default, and would raise an
    undefined-variable error in MATLAB if called with fewer than 3
    arguments -- that bug is not reproduced here.
    """
    T, is_scalar = _as_float_array(T)
    Tf = float(Tf)
    p = float(p)

    if not (0.5 <= p <= 0.8 and Tf < 0):
        raise ValueError(
            "ftheta('nic'): incorrect values for parameters p/Tf "
            "(require 0.5 <= p <= 0.8 and Tf < 0)"
        )

    frozen = T < Tf
    Theta = np.ones_like(T)
    Theta[frozen] = np.abs(Tf) ** p * np.abs(T[frozen]) ** (-p)

    dTheta = np.zeros_like(T)
    dTheta[frozen] = (
        np.abs(Tf) ** p
        * (-p)
        * np.abs(T[frozen]) ** (-p - 1)
        * np.sign(T[frozen])
    )

    return _finalize(Theta, dTheta, is_scalar)


def _hinzman(T, Tb=(-0.001, -2.0), p=10.0):
    """Hinzman, Goering & Kane (1998) exponential partition function.

    Direct translation of the "hin"/"h" branch of ftheta.m -- there is no
    standalone ftheta_hinzman.m in the source tree.

    NOTE on dTheta: the original MATLAB branch computes an intermediate
    `fp = f*p` but never actually assigns non-zero values into dTheta
    (dTheta is left as all zeros) -- this looks like an incomplete
    implementation rather than an intentional result. This Python version
    instead returns the analytically correct derivative,
        dTheta/dT = -f * exp(-f*T) / (exp(-f*Tb1) - exp(-f*Tb2))
    within the mushy interval (Tb2 < T < Tb1), and 0 outside it. Flag this
    for review if bit-for-bit MATLAB parity (including the bug) is
    required instead.
    """
    T, is_scalar = _as_float_array(T)
    Tb1, Tb2 = float(Tb[0]), float(Tb[1])
    p = float(p)

    frozen_out = T >= Tb1
    frozen_in = T <= Tb2
    mushy = (T > Tb2) & (T < Tb1)

    f = p / (Tb1 - Tb2)
    denom = np.exp(-f * Tb1) - np.exp(-f * Tb2)

    Theta = np.empty_like(T)
    Theta[frozen_out] = 1.0
    Theta[frozen_in] = 0.0
    Theta[mushy] = (np.exp(-f * T[mushy]) - np.exp(-f * Tb2)) / denom

    dTheta = np.zeros_like(T)
    dTheta[mushy] = -f * np.exp(-f * T[mushy]) / denom

    return _finalize(Theta, dTheta, is_scalar)


