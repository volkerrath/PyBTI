def cpfT_fehmn(model: dict) -> dict:
    """Pure water isobaric heat capacity [J/(kg*K)] as a function of
    temperature (deg C) and pressure (Pa), valid for P in 0.01-110 MPa and
    T in 15-350 deg C, extended below 0 C (down to -45 C) with the Speedy
    (1987) supercooled-water correlation.

    model: {"T": ..., "P": 0.1 (optional)}
    Returns {"cpf": ...}.

    Used by every site except "const": aar, bal, blz, fmk, full, lax, oku,
    olk, otn, sg3, str, syn, ull.

    Reference: Zylkovskij et al., Models and Methods Summary for the FEHMN
    Application, ECD 22, LA-UR-94-3787, Los Alamos National Laboratory,
    1994. (Low-temperature branch: Speedy, R. J., Thermodynamic properties
    of supercooled water at 1 atm, J. Phys. Chem., 1987, 91, 3354-3358.)
    Original MATLAB: vr, RWTH Aachen University, April 25, 2004.
    """
    T, is_scalar = _as_float_array(model["T"])
    P = np.broadcast_to(
        np.asarray(model.get("P", 0.1), dtype=float), T.shape
    ).copy()

    Pm = P / 1.0e6  # Pa -> MPa
    P2, P3 = Pm**2, Pm**3
    T2, T3 = T**2, T**3
    TP, T2P, TP2 = Pm * T, T2 * Pm, T * P2

    ac = [
        0.25623465e-3,
        0.10184405e-2,
        0.22554970e-4,
        0.34836663e-7,
        0.41769866e-2,
        -0.21244879e-4,
        0.25493516e-7,
        0.89557885e-4,
        0.10855046e-6,
        -0.21720560e-6,
        0.10000000e1,
        0.23513278e-1,
        0.48716386e-4,
        -0.19935046e-8,
        -0.50770309e-2,
        0.57780287e-5,
        0.90972916e-9,
        -0.58981537e-4,
        -0.12990752e-7,
        0.45872518e-8,
    ]

    a = (
        ac[0]
        + ac[1] * Pm
        + ac[2] * P2
        + ac[3] * P3
        + ac[4] * T
        + ac[5] * T2
        + ac[6] * T3
        + ac[7] * TP
        + ac[9] * T2P
        + ac[8] * TP2
    )
    b = (
        ac[10]
        + ac[11] * Pm
        + ac[12] * P2
        + ac[13] * P3
        + ac[14] * T
        + ac[15] * T2
        + ac[16] * T3
        + ac[17] * TP
        + ac[19] * T2P
        + ac[18] * TP2
    )
    da = (
        ac[4]
        + 2 * ac[5] * T
        + 3 * ac[6] * T2
        + ac[7] * Pm
        + 2 * ac[9] * TP
        + ac[8] * P2
    )
    db = (
        ac[14]
        + 2 * ac[15] * T
        + 3 * ac[16] * T2
        + ac[17] * Pm
        + 2 * ac[19] * TP
        + ac[18] * P2
    )

    cpf = (da / b - a * db / b**2) * 1.0e6

    bc = [14.2, 25.952, 128.281, -221.405, 196.894, -64.812]
    ic = T < 0.0
    Tclip = np.where(T < -45.0, -45.0, T)
    r = (Tclip[ic] + 273.15 - 227.15) / 227.15
    r2, r3, r4 = r**2, r**3, r**4
    cpf_ic = (
        bc[0] / np.sqrt(r)
        + bc[1]
        + bc[2] * r
        + bc[3] * r2
        + bc[4] * r3
        + bc[5] * r4
    )
    cpf_ic = cpf_ic * 0.99048992406520 * 1000.0 / 18.0
    cpf[ic] = cpf_ic

    return {"cpf": _result(cpf, is_scalar)}


