    r2, r3, r4 = r**2, r**3, r**4
    rho[ic] = bc[0] * np.exp(
        -227.15
        * (
            bc[2] * r
            + 0.5 * bc[3] * r2
            + (1.0 / 3.0) * bc[4] * r3
            + 0.25 * bc[5] * r4
            + 2 * bc[1] * np.sqrt(r)
        )
    )

    return {"rho": _result(rho, is_scalar)}


