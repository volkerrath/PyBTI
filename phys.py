# --- rock/matrix thermal conductivity, kmT ------------------------------


def kmT_const(model: dict) -> dict:
    """Rock thermal conductivity, temperature-independent: kmT = k.

    model: {"k": ..., "T": None (unused, optional)}
    Returns {"kmT": ...}.

    Used by: aar, blz, str, syn, const (all four of these compute the
    same temperature-independent result; they only differ in MATLAB
    argument-list bookkeeping that has no Python equivalent).
    """
    k, is_scalar = _as_float_array(model["k"])
    return {"kmT": _result(k, is_scalar)}


def kmT_clauser(model: dict) -> dict:
    """Rock thermal conductivity as a function of temperature, after
    Clauser & Huenges (1995), AGU Reference Shelf, with default
    coefficients A=0.7, B=770, T0=20 C, T1=800 C.

    model: {"km0": ..., "T": ..., "A": 0.7 (optional), "B": 770.0
            (optional), "T0": 20.0 (optional), "T1": 800.0 (optional)}
    Returns {"kmT": ...}.

    Used by: bal, full, ull, oku (oku exposes an extra unused "Pcl"
    parameter in the MATLAB signature but is otherwise the same formula
    with the same defaults).

    Original MATLAB: v.r., Nov 2, 2002.
    """
    T, is_scalar = _as_float_array(model["T"])
    km0 = np.broadcast_to(np.asarray(model["km0"], dtype=float), T.shape)
    A = model.get("A", 0.7)
    B = model.get("B", 770.0)
    T0 = model.get("T0", 20.0)
    T1 = model.get("T1", 800.0)

    if A > 0:
        kbas = A + B / (350.0 + T0)
        klim = A + B / (350.0 + T1)
        kda = A + B / (350.0 + T)
        kda = np.where(T >= T1, klim, kda)
        f = km0 / kbas
        kmT = f * kda
    else:
        kmT = km0

    return {"kmT": _result(kmT, is_scalar)}


def kmT_olk(model: dict) -> dict:
    """Rock thermal conductivity as a function of temperature, same
    formula as kmT_clauser but with coefficients fitted to Olkiluoto
    (OLK) data (A=0.416, B=97.9, T0=25 C, T1=125 C).

    model: {"km0": ..., "T": ..., "A": 0.416 (optional), "B": 97.9
            (optional), "T0": 25.0 (optional), "T1": 125.0 (optional)}
    Returns {"kmT": ...}.

    Used by: fmk, olk, otn.

    Original MATLAB: vr, Sep 13, 2014.
    """
    defaults = {"A": 0.416, "B": 97.9, "T0": 25.0, "T1": 125.0}
    merged = {**defaults, **model}
    return kmT_clauser(merged)


def kmT_lax(model: dict) -> dict:
    """Rock thermal conductivity as a function of temperature, after
    Sundberg (2009) / Rath et al. (2018) -- linear decrease with T.

    model: {"km0": ..., "T": ...}
    Returns {"kmT": ...}.

    Used by: lax.

    Original MATLAB: vr, Oct 2018.
    """
    T, is_scalar = _as_float_array(model["T"])
    km0 = np.broadcast_to(np.asarray(model["km0"], dtype=float), T.shape)

    f = 0.03e-2 * km0
    kmT = km0 - f * (T - 25.0)

    return {"kmT": _result(kmT, is_scalar)}


def kmT_sg3(model: dict) -> dict:
    """Rock thermal conductivity as a function of temperature, for the
    Kola SG3 borehole.

    model: {"k": ..., "T": ..., "A": 0.0013 (optional), "B": 0.0029
            (optional)}
    Returns {"kmT": ..., "dmT": ...} (dmT = 0.45*kmT, matching the MATLAB
    two-output form [kmT,dmT]=kmT(...); computed unconditionally here
    since Python has no nargout).

    Used by: sg3.

    Reference: Vosteen, H.-D. et al., Physics and Chemistry of the Earth,
    2003, 28, 499-509; Mottaghy, D. et al., International Journal of
    Earth Sciences (Geologische Rundschau), 2008, 97, 435-442.
    Default coefficients A, B here are the "Kola" pair from the MATLAB
    comment (0.0013, 0.0029); the commented-out alternative in the source
    was the "sedimentary" pair (0.0034, 0.0039).
    Original MATLAB: vr, March 2013.
    """
    T, is_scalar = _as_float_array(model["T"])
    k = np.broadcast_to(np.asarray(model["k"], dtype=float), T.shape)
    A = model.get("A", 0.0013)
    B = model.get("B", 0.0029)

    Tlim = 800.0
    km0 = 0.53 * k + 0.5 * np.sqrt(1.13 * k**2 - 0.42 * k)

    denom = 0.99 + T * (A - B / km0)
    denom_lim = 0.99 + Tlim * (A - B / km0)
    kmT = np.where(T <= Tlim, km0 / denom, km0 / denom_lim)
    dmT = 0.45 * kmT

    return {"kmT": _result(kmT, is_scalar), "dmT": _result(dmT, is_scalar)}


# --- rock/matrix volumetric heat capacity, rcmT -------------------------


def rcmT_direct(model: dict, *, cpmT_func) -> dict:
    """Rock volumetric heat capacity: rcmT = rm * cpmT_func(cpm, T, P),
    i.e. density times a (site-specific) specific-heat-vs-temperature
    function.

    model: {"rm": ..., "cpm": ..., "T": ..., "P": None (optional)}
    `cpmT_func` must be the matching site's cpmT_* function (one of
    cpmT_aar, cpmT_blz, cpmT_syn for the sites that use this form).
    Returns {"rcmT": ...}.

    Used by: aar, blz, str, syn.
    """
    cpmT_val = cpmT_func(
        {"cpm": model["cpm"], "T": model["T"], "P": model.get("P")}
    )["cpmT"]
    return {"rcmT": model["rm"] * cpmT_val}


def rcmT_scaled(model: dict, *, cpmT_func) -> dict:
    """Rock volumetric heat capacity: rcmT = rcm * cpmT_func(cpm, T) / cpm,
    i.e. a reference volumetric heat capacity `rcm` rescaled by the
    (site-specific) specific-heat temperature dependence.

    model: {"rcm": ..., "cpm": ..., "T": ...}
    `cpmT_func` must be the matching site's cpmT_* function (one of
    cpmT_bal, cpmT_const, cpmT_fmk, cpmT_lax, cpmT_oku for the sites that
    use this form).
    Returns {"rcmT": ...}.

    Used by: bal, fmk, full, olk, ull, const, lax, oku, otn.
    """
    cpmT_val = cpmT_func({"cpm": model["cpm"], "T": model["T"]})["cpmT"]
    return {"rcmT": model["rcm"] * cpmT_val / model["cpm"]}


def rcmT_sg3(model: dict) -> dict:
    """Rock volumetric heat capacity for the Kola SG3 borehole, computed
    directly (does not call a separate cpmT function).

    model: {"rcm": ..., "cpm": ..., "T": ...}
    Returns {"rcmT": ...}.

    Used by: sg3.

    Reference: Kola SG3 data, per the MATLAB source comment.
    """
    T, is_scalar = _as_float_array(model["T"])
    rcm = np.broadcast_to(np.asarray(model["rcm"], dtype=float), T.shape)
    cpm = np.broadcast_to(np.asarray(model["cpm"], dtype=float), T.shape)

    rcm0 = rcm / cpm
    rcmT = rcm0 * 1.0 / (0.0044 * T + 2.134)

    return {"rcmT": _result(rcmT, is_scalar)}


# --- per-site registry ---------------------------------------------------
#
# Maps every site code to the correct implementation of each property.
# rcmT entries are bound (via functools.partial) to that site's own cpmT_*
# function, since the rcmT formula itself calls back into cpmT. Every
# entry takes and returns a dict, exactly like the standalone functions
# above.

import functools as _functools

_CPMT_BY_SITE = {
    "aar": cpmT_aar,
    "bal": cpmT_bal,
    "blz": cpmT_blz,
    "const": cpmT_const,
    "fmk": cpmT_fmk,
    "full": cpmT_bal,
    "lax": cpmT_lax,
    "oku": cpmT_oku,
    "olk": cpmT_fmk,
    "otn": cpmT_fmk,
    "sg3": cpmT_sg3,
    "str": cpmT_blz,
    "syn": cpmT_syn,
    "ull": cpmT_bal,
}

_RCMT_DIRECT_SITES = {"aar", "blz", "str", "syn"}
_KMT_CONST_SITES = {"aar", "blz", "str", "syn", "const"}
_KMT_CLAUSER_SITES = {"bal", "full", "ull", "oku"}
_KMT_OLK_SITES = {"fmk", "olk", "otn"}
_CPIT_REG_SITES = {"aar", "blz", "oku", "str", "syn"}

SITE_PROPS = {}
for _site in (
    "aar",
    "bal",
    "blz",
    "const",
    "fmk",
    "full",
    "lax",
    "oku",
    "olk",
    "otn",
    "sg3",
    "str",
    "syn",
    "ull",
):

    _cpmT_site = _CPMT_BY_SITE[_site]

    if _site in _RCMT_DIRECT_SITES:
        _rcmT_site = _functools.partial(rcmT_direct, cpmT_func=_cpmT_site)
    elif _site == "sg3":
        _rcmT_site = rcmT_sg3
    else:
        _rcmT_site = _functools.partial(rcmT_scaled, cpmT_func=_cpmT_site)

    if _site in _KMT_CONST_SITES:
        _kmT_site = kmT_const
    elif _site in _KMT_CLAUSER_SITES:
        _kmT_site = kmT_clauser
    elif _site in _KMT_OLK_SITES:
        _kmT_site = kmT_olk
    elif _site == "lax":
        _kmT_site = kmT_lax
    else:  # sg3
        _kmT_site = kmT_sg3

    SITE_PROPS[_site] = {
        "cpfT": cpfT_const if _site == "const" else cpfT_fehmn,
        "cpiT": (
            cpiT_const
            if _site == "const"
            else cpiT_reg if _site in _CPIT_REG_SITES else cpiT_fukosako
        ),
        "cpmT": _cpmT_site,
        "kfT": kfT_const if _site == "const" else kfT_phillips,
        "kiT": kiT_const if _site == "const" else kiT_reg,
        "kmT": _kmT_site,
        "rcmT": _rcmT_site,
        "rhofT": rhofT_const if _site == "const" else rhofT_fehmn,
        "rhoiT": rhoiT_const if _site == "const" else rhoiT_reg,
    }

del _site, _cpmT_site, _rcmT_site, _kmT_site
