def kfT_phillips(model: dict) -> dict:
    """Formation-water thermal conductivity [W/(m*K)] as a function of
    temperature (deg C) and NaCl salinity (mass fraction, g/g). Valid
    20-330 deg C, up to 4 molal NaCl.

    model: {"T": ..., "S": 0.0 (optional)}
    Returns {"kf": ..., "kfw": ...} (kfw is the freshwater-only value,
    matching the MATLAB [kf,kfw]=kfT(...) two-output form).

    Used by every site except "const": aar, bal, blz, fmk, full, lax, oku,
    olk, otn, sg3, str, syn, ull.

    Reference: Phillips, S. L.; Igbene, A.; Fair, J. A.; Ozbek, H. &
    Tavana, M., A technical databook for geothermal energy utilization,
    Lawrence Berkeley Laboratory Report 12810, 1981, 46 p.
    Fortran source: J. J. Adams, Alberta Geological Survey, May 2001.
    Original MATLAB: V. Rath, RWTH Aachen University, April 2004.
    """
    T, is_scalar = _as_float_array(model["T"])
    S = np.broadcast_to(np.asarray(model.get("S", 0.0), dtype=float), T.shape)

    Tr = (T + 273.15) / 273.15
    Tr2, Tr3, Tr4 = Tr**2, Tr**3, Tr**4
    kfw = -0.92247 + 2.8395 * Tr - 1.8007 * Tr2 + 0.52577 * Tr3 - 0.07344 * Tr4

    saline = S > 1.0e-7
    T2 = T**2
    C = S / (1.0 + S) * 1.0e2
    C2 = C**2
    kf_saline = kfw * (
        1.0
        - (2.3434e-3 - 7.924e-6 * T + 3.924e-8 * T2) * C
        + (1.06e-5 - 2.0e-8 * T - 1.2e-10 * T2) * C2
    )
    kf = np.where(saline, kf_saline, kfw)

    return {"kf": _result(kf, is_scalar), "kfw": _result(kfw, is_scalar)}


