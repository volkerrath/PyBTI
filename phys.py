def ftheta(model: str, **kwargs) -> dict:
    """
    Fluid/ice partition function dispatcher (translation of ftheta.m /
    ftheta_new.m).

    Parameters
    ----------
    model : str
        Which formulation to use: "lun"/"l", "gal"/"g", "nic"/"n", or
        "hin"/"h" (case-insensitive). See module docstring for the
        reference behind each.
    **kwargs :
        T : array-like or scalar, temperature in deg C (required).
        Model-specific parameters (all optional, defaulting exactly as in
        the original MATLAB):
            lun: Tf=0.0, w=0.5
            gal: Tf=0.0
            nic: Tf=-0.001, p=0.5   (requires 0.5 <= p <= 0.8, Tf < 0)
            hin: Tb=[-0.001, -2.0], p=10.0

    Returns
    -------
    dict
        {"Theta": <ndarray or float>, "dTheta": <ndarray or float>},
        with 0 <= Theta <= 1.
    """
    try:
        T = kwargs.pop("T")
    except KeyError:
        raise TypeError("ftheta: missing required keyword argument 'T'")

    fun = _MODELS.get(str(model).lower())
    if fun is None:
        raise ValueError(f"ftheta: unknown model '{model}'")

    return fun(T, **kwargs)


